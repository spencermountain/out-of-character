import fs from 'node:fs'
import data from '../data/characters.js'

// Keep only what the matcher needs, so the builds stay small.
// rows are [code, name, type, replaceWith]
const rows = data
  .filter((obj) => obj.replaceWith !== undefined)
  .map((obj) => '  ' + JSON.stringify([obj.code, obj.name, obj.type, obj.replaceWith]))

const out = `// generated by scripts/data.js — do not edit\nexport default [\n${rows.join(',\n')},\n]\n`
fs.writeFileSync(new URL('../src/_data.js', import.meta.url), out)
